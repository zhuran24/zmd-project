from fractions import Fraction
from itertools import permutations
from collections import Counter
import json


def 迟滞探针(格数, 先使动, 步数=30000):
    """推测：固定判定序是分流器、整段传送带、无限供料端。

    补足：一格滞留八步，进入时相位七，每步最多移动一次；供料端只补空分流器。
    两版唯一差异是分流器尝试送货前，是否先让传送带内部能移动的物品移动。
    使动不允许传送带提前送出；传送带对外仍仅判定一次；输送方向从列表头到尾。
    为隔离局部运动，分流器先于传送带的层数关系作为给定，不重建完整断尾结构。
    """
    分流器 = [0, -1]
    带 = [[0, -1] for _ in range(格数)]
    出货时刻 = []

    def 内部移动(时刻):
        for 位 in range(格数 - 1, -1, -1):
            货 = 带[位]
            if 货 is None or 货[1] == 时刻:
                continue
            if 货[0] > 0:
                货[0] -= 1
                货[1] = 时刻
            elif 位 < 格数 - 1 and 带[位 + 1] is None:
                带[位 + 1] = [7, 时刻]
                带[位] = None

    for 时刻 in range(步数):
        if 先使动:
            内部移动(时刻)
        if 分流器 and 分流器[0] == 0 and 带[0] is None:
            带[0] = [7, 时刻]
            分流器 = None
        if 分流器 and 分流器[1] != 时刻 and 分流器[0] > 0:
            分流器[0] -= 1
            分流器[1] = 时刻
        末货 = 带[-1]
        if 末货 and 末货[0] == 0 and 末货[1] != 时刻:
            带[-1] = None
            出货时刻.append(时刻)
        内部移动(时刻)
        if 分流器 is None:
            分流器 = [7, 时刻]

    稳态时刻 = [刻 for 刻 in 出货时刻 if 刻 >= 2000]
    间隔 = [后 - 前 for 前, 后 in zip(稳态时刻, 稳态时刻[1:])]
    周期件数 = 格数 if 先使动 else 1
    周期间隔 = 间隔[:周期件数]
    assert len(间隔) > 100 * 周期件数
    assert all(距 == 周期间隔[位 % 周期件数] for 位, 距 in enumerate(间隔))
    归一产率 = Fraction(8 * 周期件数, sum(周期间隔))
    return {"格数": 格数, "先使动": 先使动, "周期间隔": 周期间隔,
            "归一产率": str(归一产率), "社区目标": str(Fraction(8 * 格数, 8 * 格数 + 1))}


def 换料探针(例号, 内部时长, 总步数=1000):
    """推测：补足为物流收料及出货、结束生产、开始生产三个阶段。

    输入相位取导论的三条时间线，之后按各自周期续上；缓存允许积料。
    上一批一件产物全部出货后才能切换，输入及输出上限各一件/步。
    内部时长取七步或八步，设计 A 未写这一项；两版对外都用两秒配方名称。
    """
    到料 = {}
    if 例号 == 1:
        到料[1] = "甲"
        for 刻 in range(2, 总步数 + 1, 16): 到料[刻] = "乙"
        for 刻 in range(10, 总步数 + 1, 16): 到料[刻] = "甲"
        用量 = 1
    elif 例号 == 2:
        for 刻 in range(1, 总步数 + 1, 8):
            到料[刻] = "甲" if (刻 - 1) // 8 % 2 == 0 else "乙"
        用量 = 1
    else:
        到料[1] = "甲"
        for 基 in range(9, 总步数 + 1, 18):
            到料[基] = "甲"
            到料[基 + 1] = "乙"
            到料[基 + 9] = "乙"
            到料[基 + 10] = "甲"
        用量 = 2
    库存 = Counter()
    在制 = None
    待出 = None
    开工 = []
    出货 = []
    下一种 = "甲"
    for 时刻 in range(1, 总步数 + 1):
        if 时刻 in 到料:
            库存[到料[时刻]] += 1
        if 待出 is not None:
            出货.append([时刻, 待出])
            待出 = None
        if 在制 is not None and 时刻 >= 在制[1]:
            待出 = 在制[0]
            在制 = None
        if 在制 is None and 待出 is None and 库存[下一种] >= 用量:
            库存[下一种] -= 用量
            在制 = (下一种, 时刻 + 内部时长)
            开工.append([时刻, 下一种])
            下一种 = "乙" if 下一种 == "甲" else "甲"
    同种时刻 = [刻 for 刻, 种 in 开工 if 种 == "甲"]
    同种间隔 = [后 - 前 for 前, 后 in zip(同种时刻, 同种时刻[1:])]
    assert len(set(同种间隔)) == 1
    return {"例号": 例号, "内部时长": 内部时长, "一轮步数": 同种间隔[0],
            "前六次开工": 开工[:6], "前六次出货": 出货[:6]}


def 满箱探针(箱数):
    """推测：源带、各箱、箱间一格带、末端带均满载，末端在第零步恢复。

    各传送带按下游先算、各箱在全部传送带后输出，输入即时入箱。
    所有初始带货已满足滞留；新货入带八步后才可离带；每箱初始三百件。
    只观测源带第一次能向首箱送出，所用连接是运输单位与非运输单位连接。
    """
    箱 = [300] * 箱数
    带到期 = [-8] * (箱数 + 1)
    for 时刻 in range(20):
        for 位 in range(箱数, -1, -1):
            if 带到期[位] is None or 时刻 < 带到期[位]:
                continue
            if 位 == 箱数:
                带到期[位] = None
            elif 箱[位] < 300:
                箱[位] += 1
                带到期[位] = None
                if 位 == 0:
                    return 时刻
        for 位 in range(箱数 - 1, -1, -1):
            if 箱[位] > 0 and 带到期[位 + 1] is None:
                箱[位] -= 1
                带到期[位 + 1] = 时刻 + 8
    raise AssertionError("观测期内源带未流通")


def 三上游探针():
    """推测：汇流器先清空，然后左分流器、传送带、右分流器按给定序各试一次。

    两个分流器不参加共同收货；这里只有一条非分流器上游，因此其收货组为单元。
    初始相位全对齐、三支满载，汇流器八步输出一件，空位由第一次成功送货者占据。
    不推演建造历史到固定序的映射。
    """
    行 = []
    for 序 in permutations(["左分流器", "传送带", "右分流器"]):
        数 = Counter()
        for _ in range(1000):
            空 = True
            for 名 in 序:
                if 空:
                    数[名] += 1
                    空 = False
        assert 数[序[0]] == 1000 and len(数) == 1
        行.append({"固定序": 序, "独占者": 序[0]})
    return 行


def 准入口探针(恢复):
    """估算：输入每八步一件，窗口四十步额度五件，每一千二百步处理边界。

    推测：恢复可以是保留窗口、重置窗口与已用额度、重置剩余时间但保留已用额度。
    设计 A 只说重置剩余时间，未说明已用额度如何恢复；这里分别计算其影响。
    """
    到期 = None
    已用 = 0
    放行 = 0
    总步数 = 28800
    for 时刻 in range(总步数):
        if 时刻 and 时刻 % 1200 == 0:
            if 恢复 == "窗口与额度全重置":
                到期 = None
                已用 = 0
            elif 恢复 == "剩余时间置四十步、保留额度":
                到期 = 时刻 + 40
        if 时刻 % 8:
            continue
        if 到期 is None or 时刻 >= 到期:
            到期 = 时刻 + 40
            已用 = 0
        if 已用 < 5:
            已用 += 1
            放行 += 1
    return {"恢复": 恢复, "两小时放行": 放行, "较无边界减少": 3600 - 放行,
            "处理边界次数": 23}


def 轮询状态探针():
    """推测：布局与两支库存相同，成功历史不同，下一次轮询结果不同。"""
    通道 = ["甲", "乙"]
    行 = []
    for 上次 in range(2):
        库存 = [1, 1]
        接受 = None
        for 距离 in range(1, len(通道) + 1):
            位 = (上次 + 距离) % len(通道)
            if 库存[位] > 0:
                库存[位] -= 1
                接受 = 通道[位]
                break
        行.append({"上次成功": 通道[上次], "下一次": 接受})
    assert [项["下一次"] for 项 in 行] == ["乙", "甲"]
    return 行


def 主程序():
    迟滞 = [迟滞探针(数, 使动) for 数 in (1, 2, 3, 6) for 使动 in (False, True)]
    for 行 in 迟滞:
        if 行["先使动"]:
            assert 行["归一产率"] == 行["社区目标"]
    换料 = [换料探针(例, 时长) for 时长 in (7, 8) for 例 in (1, 2, 3)]
    assert [行["一轮步数"] for 行 in 换料[:3]] == [16, 16, 18]
    assert [行["一轮步数"] for 行 in 换料[3:]] == [18, 18, 18]
    满箱 = [{"箱数": 数, "源带首次恢复步": 满箱探针(数)} for 数 in range(1, 7)]
    assert all(行["箱数"] == 行["源带首次恢复步"] for 行 in 满箱)
    准入口 = [准入口探针(法) for 法 in ("保留窗口", "窗口与额度全重置", "剩余时间置四十步、保留额度")]
    assert [行["两小时放行"] for 行 in 准入口] == [3600, 3600, 3485]
    结果 = {"说明": "独立局部补足探针，不代表游戏实测或设计 A 的完整实现",
            "迟滞": 迟滞, "换料": 换料, "满箱": 满箱, "三上游": 三上游探针(),
            "准入口": 准入口, "轮询历史": 轮询状态探针(),
            "成本复算": {"每天核心CPU秒": 0.001 * 86400,
                         "每秒八千判定对应纳秒": 1_000_000 / 8000,
                         "一百万人十二小时补算核时": 1_000_000 * 12 * 3600 * 0.001 / 3600,
                         "每边界零点四件十小时积累": 0.4 * 12 * 10}}
    print(json.dumps(结果, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    主程序()
