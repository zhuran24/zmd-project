# ---- 第十一节：把准入口这一头放开穷举。头一件算整秒后第 1 步到准入口；名额至少占 M 步、在步数对 4 余 B 的那一步空；
# 进准入口到进收货箱的步数对 4 余 X。看「隔着带子」和「紧接桥接器」两行各自对得上哪些。


def 算门(头, 上限, M, X, B, 件数=20):
    名额, 进 = [], []
    for g in [头 + 9 * i for i in range(件数)]:
        占着 = sorted(x for x in 名额 if x > g)
        e = g if len(占着) < 上限 else 占着[len(占着) - 上限]
        if 进:
            e = max(e, 进[-1])
        t = e + M
        名额.append(t + (B - t) % 4)
        进.append(e)
    秒 = [math.ceil((e + X) / 4) for e in 进]
    return [x - 秒[0] for x in 秒]


紧接桥接器_上限4 = [0, 2, 4, 6, 9, 11, 14, 16, 19, 21, 24, 26, 29, 31, 34, 36, 39, 41]
print('准入口这一头放开穷举（名额 33—43 步）')
for 名, 读到的 in [('隔着带子', 今天_上限4), ('紧接桥接器', 紧接桥接器_上限4)]:
    对 = set()
    for 头 in range(4):
        for M in range(33, 44):
            for B in range(4):
                for X in range(4, 13):
                    if 算门(头, 4, M, X, B)[:len(读到的)] == 读到的:
                        k = (1 - 头) % 4          # 整体挪步，把头一件挪到第 1 步
                        对.add((M, (B + k) % 4, (X - k) % 4))
    print(' ', 名, '对得上的（至少占几步、空在余几、进箱余几）：', sorted(对))
