"""每件隔 9 步的货流，过一个中间单位、一格带、一个限速的物品准入口（紧贴收货箱），算收货箱里各件到的整秒。

拿来核对实测-2026-11-25「每件隔 9 步的货流过精炼炉、穿过协议储存箱」一节的读数，2026-11-26 写的（实测-2026-11-26 第十节）。
步数的算法和规则模型一样：带子、准入口每格 8 步；名额在整秒后第 4 步（步数是 4 的整倍数的那一步）空出来，
至少占 38 步；等着名额的货在名额空出来的那一步进去；看得到的时刻是步数除以 4 往上取整。
「模型 8 步」这一种的四行和规则模型当时算的预计一样，用来对这份脚本自己。

2026-11-26 第五次开游戏以后加了最后两段（实测-2026-11-26 第十一节）：
同样的货流过精炼炉直接进无线传输的箱子；把名额从「至少占 38 步」换成「至少占 37 步」重算前面各行。
后一段是因为第十一节量到：这几行用的摆法（限速的准入口紧贴收货箱）下，不带中间单位的货流读到的也不是「38 步」那一行，
照「37 步」才逐件对得上；所以前面照 38 步做的穷举（32 种、16 种）要照最后一段重看。
规则模型在第十一节以后也改成了「至少占 37 步」（前面几段里「模型」的各行是照当时的 38 步算的，留着没动）。
最后一段的穷举把头一件都当成第 1 步到准入口，没有算分流器：紧接桥接器的那一行它得出的两种里没有「37 步、整秒那一步空」，
规则模型整套算是对得上的（等名额的货排到分流器里，晚 1 步才送出）。
"""
import math


def 算(头一件到的步, 中间单位要几步, 上限, 件数=14, 名额至少=38):
    到中间单位 = [头一件到的步 + 9 * i for i in range(件数)]
    到准入口 = [a + 中间单位要几步(a) + 8 for a in 到中间单位]
    名额, 进准入口 = [], []
    for g in 到准入口:
        if 上限 is None:
            e = g
        else:
            占着 = sorted(x for x in 名额 if x > g)
            e = g if len(占着) < 上限 else 占着[len(占着) - 上限]
            if 进准入口 and e < 进准入口[-1]:
                e = 进准入口[-1]
            t = e + 名额至少
            名额.append(t + (-t) % 4)
        进准入口.append(e)
    秒 = [math.ceil((e + 8) / 4) for e in 进准入口]
    return [x - 秒[0] for x in 秒]


def 间隔(l):
    return [b - a for a, b in zip(l, l[1:])]


print('过精炼炉（原料依次在整秒后第 1、2、3、4 步到炉子）')
print('  实测：不限 间隔 2 2 3 2 2 2 3…；上限 4 各件在 0 2 4 7 9 11 14 16 19 21；上限 3 间隔 2 2 5 然后 2 3 5；上限 2 间隔 2 7 然后 2 8')
for 名, f in [('模型：一律 8 步', lambda a: 8),
              ('整秒那一步到的 9 步，别的 8 步', lambda a: 9 if a % 4 == 0 else 8),
              ('一律 9 步', lambda a: 9)]:
    print(' ', 名)
    for k in [None, 4, 3, 2]:
        r = 算(1, f, k)
        print('    上限', k, '各件在', r[:12], '间隔', 间隔(r)[:11])

print('穿过仓储模式的箱子')
print('  实测：上限 4 各件在 0 2 4 6 9 11 13 16 19 21 23 26')
print('  模型：当步穿过，头一件第 1 步到        ', 算(1, lambda a: 0, 4)[:12])
print('  头一件整秒那一步到，这样的货晚一步出箱', 算(0, lambda a: 1 if a % 4 == 0 else 0, 4)[:12])

# ---- 穷举：头一件是整秒后第几步到的，各步到的货各要几步，哪些组合和读数逐件相同
import itertools

炉_不限 = [2, 2, 3, 2, 2, 2, 3, 2, 2, 2, 3, 2, 2, 2]
炉_上限4 = [0, 2, 4, 7, 9, 11, 14, 16, 19, 21]
炉_上限3 = [2, 2, 5] + [2, 3, 5] * 3
炉_上限2 = [2, 7] + [2, 8] * 4
箱_上限4 = [0, 2, 4, 6, 9, 11, 13, 16, 19, 21, 23, 26]

print('穷举 过精炼炉：整秒后第 1、2、3、4 步到的原料各要 7—10 步')
for 头 in [1, 2, 3, 4]:
    for d in itertools.product([7, 8, 9, 10], repeat=4):
        f = lambda a, d=d: d[(a - 1) % 4]
        if (间隔(算(头, f, None, 16))[:14] == 炉_不限 and 算(头, f, 4, 16)[:10] == 炉_上限4
                and 间隔(算(头, f, 3, 16))[:12] == 炉_上限3 and 间隔(算(头, f, 2, 16))[:10] == 炉_上限2):
            print('  头一件第', 头, '步到；各要', d)

print('穷举 穿过箱子：整秒后第 1、2、3、4 步到的货各晚 0—2 步出箱')
for 头 in [1, 2, 3, 4]:
    for d in itertools.product([0, 1, 2], repeat=4):
        f = lambda a, d=d: d[(a - 1) % 4]
        if 算(头, f, 4)[:12] == 箱_上限4:
            print('  头一件第', 头, '步到；各晚', d)

# ---- 2026-11-26 第五次开游戏：同样的货流过精炼炉以后直接进无线传输箱 T（中间两格带）。
# T 每 40 步传输一次，落在整秒那一步；传输那一步才到的货留在箱里（实测-2026-11-25、11-26 第十节量的）。
# 实测（读箱/watch-九步货流过精炼炉进传输箱-*.txt）：读箱每秒一次，九次传输里正好一次看到 4 变 1，下一次 5 变 0，别的都是 4 变 0。


def 传输箱(中间单位要几步, 件数=200):
    到 = [1 + 9 * i + 中间单位要几步(1 + 9 * i) + 16 for i in range(件数)]
    出 = []
    for t in range(400, 9 * 件数 - 400, 40):
        # 读箱每秒看一次：和传输同一秒、早一两三步到的货，到了就被送走，箱里看不到它
        前 = sum(1 for a in 到 if t - 40 <= a <= t - 4)     # 传输前一秒看到的件数（上一次传输那一步到的也在里面）
        后 = sum(1 for a in 到 if a == t)                   # 传输那一秒看到的件数
        出.append((前, 后))
    return 出[:9]


print('穷举 过精炼炉 + 直接进无线传输箱：九次传输里各是几件变几件')
剩下 = []
for d in itertools.product([7, 8, 9, 10], repeat=4):
    f = lambda a, d=d: d[(a - 1) % 4]
    对 = [头 for 头 in [1, 2, 3, 4]
         if (间隔(算(头, f, None, 16))[:14] == 炉_不限 and 算(头, f, 4, 16)[:10] == 炉_上限4
             and 间隔(算(头, f, 3, 16))[:12] == 炉_上限3 and 间隔(算(头, f, 2, 16))[:10] == 炉_上限2)]
    if not 对:
        continue
    r = 传输箱(f)
    几次 = sum(1 for 前, 后 in r if 后 > 0)
    if 几次 == 1 and sorted(r) == sorted([(4, 0)] * 7 + [(4, 1), (5, 0)]):
        剩下.append(d)
    print('  各要', d, '头一件可以是第', 对, '步到；九次传输', ' '.join(f'{a}变{b}' for a, b in r), '→', '对得上' if 几次 == 1 else '对不上')
print('和这次读数也对得上的：', 剩下)
for 名, f in [('模型：一律 8 步', lambda a: 8), ('一律 9 步', lambda a: 9)]:
    print(' ', 名, ' '.join(f'{a}变{b}' for a, b in 传输箱(f)))


