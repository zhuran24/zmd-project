"""点重置放的两件连过 1、2、3 台制造单位再进限速的准入口：哪几种「制造单位各要几步」对得上读数。
不靠规则模型，只照步数算（带子、准入口每格 8 步，不改货落在整秒里的步）。

候选：`九步货流过精炼炉和箱子-三种说法各算一遍.py` 末尾剩下的 9 种（11-25 过精炼炉的四行都对得上、出口带也排得开）。
每种是 (t1, t2, t3, t4)：原料在整秒后第 1、2、3、4 步到制造单位，到产物上出口带各要几步。
另一个没定的：点重置放的头一件是这一秒的第几步进准入口的（e = 1、2、3；第 4 步已经排除）。

读数（实测-2026-11-26 第十二节）：
  过 1 台、2 台：两件进收货箱隔 9 秒（头一件不是在整秒那一步进后面的准入口）；
  过 3 台：隔 10 秒（头一件正好在整秒那一步进），头一件在面板数字变 1 以后 26 秒进箱。
"""
from itertools import product

候选 = [(8, 7, 9, 9), (8, 8, 9, 9), (8, 9, 9, 9), (9, 8, 9, 9), (9, 8, 9, 10),
      (9, 9, 9, 9), (9, 9, 9, 10), (10, 9, 9, 9), (10, 9, 9, 10)]


def 步(p):            # 整秒后第几步：1、2、3、4
    return (p - 1) % 4 + 1


def 连过(t, e, k):
    """头一件第 e 步进准入口，连过 k 台。返回 (到后面那个准入口时是第几步, 进收货箱是点重置以后第几步)。
    线路照实测：准入口 8 步、一格带 8 步到第一台；三个位置之间的带子、不放制造单位时换上的带子都是 8 步的整倍数。
    三台都在时，除了制造单位以外一共 10 格（准入口、一格带、四格带、两格带、一格带、后面的准入口），80 步。"""
    s = e + 16                      # 到第一台
    for _ in range(k):
        s += t[步(s) - 1]
    return 步(s), None if k != 3 else s - 16 + 80


for t, e in product(候选, (1, 2, 3)):
    r1, r2, r3 = 连过(t, e, 1)[0], 连过(t, e, 2)[0], 连过(t, e, 3)
    行 = r1 != 4 and r2 != 4 and r3[0] == 4 and (r3[1] + 3) // 4 - 1 == 26
    if 行:
        # 限速放行的货是整秒那一步（第 4 步）进准入口的，连过三台以后落在第几步
        p = 4
        for _ in range(3):
            p = 步(p + t[p - 1])
        print("对得上：各要", t, "，点重置的头一件第", e, "步进准入口｜限速放行的单件连过三台以后落在第", p, "步，",
              "赶得上同一秒的传输（十档里有 0、没有 10）" if p != 4 else "赶不上（十档里有 10、没有 0）")
