    '归甲要有把握：推导里每一步用到的规则句都要对过现行文本。拿不准就归戊并说明。也不要只因为条文或依据里出现了某个旧词就归丙或丁，要看推导实际用没用到变了的东西；依据行里列了旧名词而推导其实用不到的，照实写。',
