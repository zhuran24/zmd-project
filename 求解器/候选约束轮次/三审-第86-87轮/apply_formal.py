    '    据：物品格、存货/取货物品格、缓存格、中制造单位、制造、配方、需电功能、开关、移动、滞留、判定、轮询、取货优先级、'
    '传送带、桥接器、物品准入口、零干预运行、离线、判定次序、接通先后、判定先后\n'
