NEW_DEF = '采种单元及其 L1、L2、回路存量 Φ 同「采种单元的回路存量下界」，这里四条进路都是专用进路。接法：'

OLD_JU = '拿取成品、循环态、取货口配置、端口速率、专用进路下缓存格不空的传递'
NEW_JU = '拿取成品、循环态、取货口配置、端口速率、专用进路下缓存格不空的传递、采种单元的回路存量下界'

OLD_K = '段首这个格里的件数是 k 的倍数时'
NEW_K = '段首时刻的判定之前这个格里的件数是 k 的倍数时'


def once(text, old, new):
    assert text.count(old) == 1, (old[:40], text.count(old))
    return text.replace(old, new)


def main():
    text = P.read_text()
    lines = text.split('\n')
    # 一、新条插在「植物专机一一配对满库存不断料」的据行之后
    i = next(k for k, l in enumerate(lines) if l.startswith('植物专机一一配对满库存不断料：'))
    assert lines[i + 1].startswith('    据：')
    assert not any(l.startswith('采种单元的回路存量下界：') for l in lines)
    lines[i + 2:i + 2] = NEW.rstrip('\n').split('\n')
    text = '\n'.join(lines)
    # 二、三
    text = once(text, OLD_DEF, NEW_DEF)
    text = once(text, OLD_JU, NEW_JU)
    text = once(text, OLD_K, NEW_K)
    P.write_text(text)
    heads = [l.split('：')[0] for l in text.split('\n') if l and not l.startswith(' ') and '：' in l]
    print(len(heads), heads)


if __name__ == '__main__':
    main()
