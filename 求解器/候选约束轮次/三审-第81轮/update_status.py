def patch(path, section_head, next_head, items):
    lines = path.read_text(encoding="utf-8").split("\n")
    start = next(i for i, ln in enumerate(lines) if ln.startswith(section_head))
    end = next(i for i in range(start + 1, len(lines)) if lines[i].startswith(next_head))
    for name, (old_status, new_status) in items.items():
        hits = [i for i in range(start, end) if lines[i].startswith(name + "：")]
        assert len(hits) == 1, (name, hits)
        k = next(i for i in range(hits[0] + 1, end) if lines[i].startswith("    状态："))
        assert lines[k] == old_status, (name, lines[k])
        lines[k] = new_status
    return lines


