def patch(path, table):
    lines = path.read_text().split('\n')
    done = set()
    for i, line in enumerate(lines):
        for head, status in table.items():
            if line.startswith(head):
                block = []
                for k in range(i + 1, len(lines)):
                    if not lines[k].startswith('    '):
                        break
                    block.append(k)
                js = [k for k in block if lines[k].startswith('    状态：')]
                if not js:
                    continue  # 复核节里的同名结论行，没有状态行
                j = js[0]
                assert lines[j] == OLD, (head, lines[j])
                lines[j] = '    状态：' + status
                assert head not in done
                done.add(head)
    assert done == set(table), set(table) - done
    return '\n'.join(lines)


