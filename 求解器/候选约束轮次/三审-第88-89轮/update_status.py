def patch(path, table):
    lines = path.read_text().split('\n')
    done = set()
    for i, line in enumerate(lines):
        for head, (old, status) in table.items():
            if line.startswith(head):
                j = i + 1
                while lines[j].startswith('    ') and not lines[j].startswith('    状态：'):
                    j += 1
                if not lines[j].startswith('    状态：'):
                    continue      # 复核轮次一节里的同名结论行，没有状态行
                assert lines[j] == old, (head, lines[j])
                lines[j] = '    状态：' + status
                assert head not in done
                done.add(head)
    assert done == set(table), set(table) - done
    return '\n'.join(lines)


