def once(text, old, new):
    assert text.count(old) == 1, (old[:40], text.count(old))
    return text.replace(old, new)


def main():
    text = SUF.read_text()
    assert '采种单元不断料：' not in text
    lines = text.split('\n')
    i = next(k for k, l in enumerate(lines) if l.startswith('采种单元的回路存量下界：'))
    assert lines[i + 1].startswith('    据：')
    lines[i + 2:i + 2] = NEW_ITEM.rstrip('\n').split('\n')
    text = '\n'.join(lines)
    text = once(text, OLD_SKEL_HEAD, NEW_SKEL_HEAD)
    text = once(text, OLD_SKEL_TAIL, NEW_SKEL_TAIL)
    text = once(text, OLD_SRC, NEW_SRC)
    SUF.write_text(text)
    heads = [l.split('：')[0] for l in text.split('\n') if l and not l.startswith(' ') and '：' in l]
    print(len(heads), heads)

    text = CON.read_text()
    text = once(text, OLD_STOP, NEW_STOP)
    text = once(text, OLD_STOP_JU, NEW_STOP_JU)
    CON.write_text(text)
    rows = [l for l in text.split('\n') if l and not l.startswith(' ') and '：' in l and not l.endswith('：')]
    print(len(rows) - 1)   # 首行「由规则推出的约束」不含全角冒号后正文，不计


if __name__ == '__main__':
    main()
